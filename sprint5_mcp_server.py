@app.get("/tools/get_stockout_risk")
def get_stockout_risk(
    warehouse: Optional[str] = None,
    weeks_ahead: int = 2,
    top_n: int = 10
):
    """
    Returns top N SKUs at highest stockout risk.
    This is the most used tool — planners call this every Monday morning.
    
    Parameters:
        warehouse: filter to one warehouse (optional)
        weeks_ahead: how many weeks to look ahead (1-4)
        top_n: how many SKUs to return
    """
    
    # Start with full summary
    result = summary.copy()
    
    # Filter by warehouse if provided
    if warehouse:
        result = result[
            result['warehouse'].str.lower() == warehouse.lower()
        ]
        
        # If warehouse not found return clear error
        if result.empty:
            raise HTTPException(
                status_code=404,
                detail=f"Warehouse '{warehouse}' not found. Available: Atlanta, Chicago, Dallas, Newark"
            )
    
    # Sort by risk — lowest weeks of supply first = most urgent first
    result = result.sort_values('weeks_of_supply', ascending=True)
    
    # Take top N
    result = result.head(top_n)
    
    # Build clean response
    items = []
    for _, row in result.iterrows():
        items.append({
            "sku_id": row['sku_id'],
            "warehouse": row['warehouse'],
            "risk_level": row['risk'],
            "weeks_of_supply": row['weeks_of_supply'],
            "avg_weekly_demand": round(row['avg_demand'], 0),
            "current_inventory": int(row['last_inventory']),
            "action": (
                "Reorder immediately" if row['risk'] == 'HIGH'
                else "Monitor closely" if row['risk'] == 'MEDIUM'
                else "Stock adequate"
            )
        })
    
    return {
        "tool": "get_stockout_risk",
        "warehouse_filter": warehouse or "All warehouses",
        "total_results": len(items),
        "results": items,
        "summary": f"{len([i for i in items if i['risk_level']=='HIGH'])} HIGH risk SKUs found"
    }


