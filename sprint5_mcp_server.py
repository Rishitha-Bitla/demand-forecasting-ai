@app.get("/tools/get_sku_forecast")
def get_sku_forecast(sku_id: str, warehouse: str):
    """
    Returns detailed forecast for one specific SKU in one warehouse.
    Planners use this when they want to drill into one product.
    """
    
    # Find this specific SKU in this warehouse
    result = summary[
        (summary['sku_id'].str.lower() == sku_id.lower()) &
        (summary['warehouse'].str.lower() == warehouse.lower())
    ]
    
    # If not found return clear error
    if result.empty:
        raise HTTPException(
            status_code=404,
            detail=f"SKU '{sku_id}' in '{warehouse}' not found"
        )
    
    row = result.iloc[0]
    
    # Get recent sales history for this SKU
    history = df[
        (df['sku_id'].str.lower() == sku_id.lower()) &
        (df['warehouse'].str.lower() == warehouse.lower())
    ].tail(8)
    
    # Simple 4 week forecast based on recent average
    recent_avg = history['demand'].mean()
    forecasts = []
    for week in range(1, 5):
        forecasts.append({
            "week": week,
            "forecast_demand": int(recent_avg),
            "risk": row['risk']
        })
    
    return {
        "tool": "get_sku_forecast",
        "sku_id": sku_id,
        "warehouse": warehouse,
        "current_inventory": int(row['last_inventory']),
        "avg_weekly_demand": round(row['avg_demand'], 1),
        "weeks_of_supply": row['weeks_of_supply'],
        "risk_level": row['risk'],
        "four_week_forecast": forecasts,
        "recommendation": (
            f"Current inventory of {int(row['last_inventory'])} units "
            f"covers {row['weeks_of_supply']} weeks of demand. "
            + (
                "Reorder immediately." if row['risk'] == 'HIGH'
                else "Monitor stock levels." if row['risk'] == 'MEDIUM'
                else "Stock levels adequate."
            )
        )
    }



