@app.get("/tools/get_sales_history")
def get_sales_history(
    sku_id: str,
    warehouse: str,
    last_n_weeks: int = 12
):
    """
    Returns recent sales history for one SKU in one warehouse.
    Claude uses this to explain WHY a forecast looks the way it does.
    """
    
    # Filter to this SKU and warehouse
    history = df[
        (df['sku_id'].str.lower() == sku_id.lower()) &
        (df['warehouse'].str.lower() == warehouse.lower())
    ].tail(last_n_weeks)
    
    # If not found return error
    if history.empty:
        raise HTTPException(
            status_code=404,
            detail=f"No history found for '{sku_id}' in '{warehouse}'"
        )
    
    # Calculate summary stats from history
    avg_demand  = round(history['demand'].mean(), 1)
    max_demand  = int(history['demand'].max())
    min_demand  = int(history['demand'].min())
    promo_weeks = int(history['is_promo'].sum())
    
    # Check trend — is demand going up or down?
    first_half  = history['demand'].iloc[:last_n_weeks//2].mean()
    second_half = history['demand'].iloc[last_n_weeks//2:].mean()
    
    if second_half > first_half * 1.05:
        trend = "increasing"
    elif second_half < first_half * 0.95:
        trend = "decreasing"
    else:
        trend = "stable"
    
    # Build weekly data list
    weekly = []
    for _, row in history.iterrows():
        weekly.append({
            "date": str(row['date'])[:10],
            "demand": int(row['demand']),
            "inventory": int(row['inventory']),
            "promo_week": bool(row['is_promo'])
        })
    
    return {
        "tool": "get_sales_history",
        "sku_id": sku_id,
        "warehouse": warehouse,
        "weeks_of_history": last_n_weeks,
        "average_weekly_demand": avg_demand,
        "max_weekly_demand": max_demand,
        "min_weekly_demand": min_demand,
        "promo_weeks_in_period": promo_weeks,
        "demand_trend": trend,
        "weekly_data": weekly
    }



