@app.get("/tools/get_warehouse_summary")
def get_warehouse_summary(warehouse: str):
    """
    Returns overall health summary for one warehouse.
    Claude uses this to answer 'how is Atlanta doing this week?'
    """
    
    # Filter to this warehouse
    wh_data = summary[
        summary['warehouse'].str.lower() == warehouse.lower()
    ]
    
    # If not found return error
    if wh_data.empty:
        raise HTTPException(
            status_code=404,
            detail=f"Warehouse '{warehouse}' not found. Available: Atlanta, Chicago, Dallas, Newark"
        )
    
    # Count risk levels
    high   = len(wh_data[wh_data['risk'] == 'HIGH'])
    medium = len(wh_data[wh_data['risk'] == 'MEDIUM'])
    low    = len(wh_data[wh_data['risk'] == 'LOW'])
    total  = len(wh_data)
    
    # Health score — percentage of SKUs at LOW risk
    health_score = round((low / total) * 100, 1)
    
    # Top 3 most urgent SKUs
    top_risks = wh_data.sort_values(
        'weeks_of_supply', ascending=True
    ).head(3)[['sku_id','weeks_of_supply','risk']].to_dict('records')
    
    # Overall status
    if high > 0:
        status = "ATTENTION NEEDED"
    elif medium > total * 0.5:
        status = "MONITOR CLOSELY"
    else:
        status = "HEALTHY"
    
    return {
        "tool": "get_warehouse_summary",
        "warehouse": warehouse,
        "overall_status": status,
        "health_score": health_score,
        "total_skus": total,
        "risk_breakdown": {
            "HIGH": high,
            "MEDIUM": medium,
            "LOW": low
        },
        "top_3_urgent_skus": top_risks,
        "summary": (
            f"{warehouse} warehouse has {high} HIGH risk, "
            f"{medium} MEDIUM risk, and {low} LOW risk SKUs. "
            f"Overall health score: {health_score}%. "
            f"Status: {status}."
        )
    }


